#!/bin/sh
# =============================================================================
# tools/gen-expect.sh — generate an expectation set from a layer checkout
#
# Usage:
#   tools/gen-expect.sh <layer-checkout> [output]
#
#   <layer-checkout>  a meta-foundries or meta-lmp git checkout
#   [output]          file to write (default: stdout), e.g.
#                     profiles/meta-foundries/expect/blacksail.sh
#
# Reads the recipe pins (SRCREV, PV, BRANCH) and the layer defaults the
# profiles check, and writes them as FIOCHECK_* defaults. Distro choices
# (distro name, OSTREE_OSNAME) are left to the developer and not emitted. Values use
# : "${VAR:=value}" so the environment and machine files still override them.
# Regenerate whenever the layer moves a pin; the diff is the review.
# =============================================================================
set -eu

layer="${1:?usage: gen-expect.sh <layer-checkout> [output]}"
out="${2:-}"
[ -d "${layer}" ] || { echo "not a directory: ${layer}" >&2; exit 2; }

# bbvar <file> <VAR> [override] — first value of VAR (or VAR:<override>)
bbvar() {
    local name="$2"
    [ -n "${3:-}" ] && name="$2:$3"
    sed -n "s/^${name}[[:space:]]*[?:]*=[[:space:]]*\"\\([^\"]*\\)\".*/\\1/p" "$1" 2>/dev/null | head -n 1
}

# first <glob> — first existing file matching a glob
first() {
    for f in $1; do [ -f "${f}" ] && { printf '%s' "${f}"; return; }; done
}

short() { printf '%s' "$1" | cut -c1-7; }

rev="$(git -C "${layer}" rev-parse --short HEAD 2>/dev/null || echo unknown)"

if [ -f "${layer}/conf/layer.conf" ] && grep -q 'meta-foundries' "${layer}/conf/layer.conf"; then
    kind="meta-foundries"
    series="$(bbvar "${layer}/conf/layer.conf" LAYERSERIES_COMPAT_meta-foundries)"
    aklite="$(first "${layer}/recipes-sota/aktualizr-lite/aktualizr-lite_*.bb")"
    composectl="$(first "${layer}/recipes-containers/composeapp/composectl_*.bb")"
    fioconfig="$(first "${layer}/recipes-support/fioconfig/fioconfig_*.bb")"
    register="$(first "${layer}/recipes-sota/fio-device-register/fio-device-register_*.bb")"
    aklite_rev="$(bbvar "${aklite}" SRCREV)"
    aklite_ref="PV $(bbvar "${aklite}" PV), branch $(bbvar "${aklite}" BRANCH)"
    sota_client="$(bbvar "${layer}/conf/layer.conf" SOTA_CLIENT)"
    inc="${layer}/dynamic-layers/virtualization-layer/recipes-containers/docker/docker-moby-foundries.inc"
    tmpl="${layer}/dynamic-layers/virtualization-layer/recipes-containers/docker/files/daemon.json.in"
elif [ -f "${layer}/meta-lmp-base/conf/layer.conf" ]; then
    kind="meta-lmp"
    series="$(bbvar "${layer}/meta-lmp-base/conf/layer.conf" LAYERSERIES_COMPAT_meta-lmp-base)"
    base="${layer}/meta-lmp-base"
    aklite="${base}/recipes-sota/aktualizr/aktualizr_%.bbappend"
    composectl="${base}/recipes-containers/composeapp/composectl_git.bb"
    fioconfig="${base}/recipes-support/fioconfig/fioconfig_git.bb"
    register="${base}/recipes-sota/lmp-device-register/lmp-device-register_git.bb"
    aklite_rev="$(bbvar "${aklite}" SRCREV lmp)"
    aklite_ref="branch $(bbvar "${aklite}" BRANCH lmp)"
    sota_client="$(bbvar "${base}/conf/distro/lmp.conf" SOTA_CLIENT)"
    inc=""
    tmpl=""
else
    echo "${layer}: neither meta-foundries nor meta-lmp" >&2
    exit 2
fi

composectl_rev="$(bbvar "${composectl}" SRCREV)"
fioconfig_rev="$(bbvar "${fioconfig}" SRCREV)"
fioconfig_units="$(bbvar "${fioconfig}" 'SYSTEMD_SERVICE:${PN}')"
register_rev="$(bbvar "${register}" SRCREV)"

# daemon.json entries: the template's scalar keys with @@VAR@@ defaults filled
daemon_config=""
if [ -n "${tmpl}" ] && [ -f "${tmpl}" ]; then
    max_dl="$(bbvar "${inc}" DOCKER_MAX_CONCURRENT_DOWNLOADS)"
    max_try="$(bbvar "${inc}" DOCKER_MAX_DOWNLOAD_ATTEMPTS)"
    daemon_config="$(sed -e "s/@@MAX_CONCURRENT_DOWNLOADS@@/${max_dl}/" \
                         -e "s/@@MAX_DOWNLOAD_ATTEMPTS@@/${max_try}/" "${tmpl}" \
        | sed -n 's/^[[:space:]]*"\([^"]*\)":[[:space:]]*"\{0,1\}\([^",{]*\)"\{0,1\},\{0,1\}[[:space:]]*$/\1=\2/p' \
        | tr '\n' ' ' | sed 's/ $//')"
fi

emit() {
    cat <<EOF
# =============================================================================
# Expectation set: ${kind} ${series}
# Generated by tools/gen-expect.sh from ${kind} @ ${rev} — do not edit.
# Regenerate: tools/gen-expect.sh <${kind} checkout> <this file>
# =============================================================================

# aktualizr-lite ${aklite_ref} (${aklite_rev})
: "\${FIOCHECK_AKLITE_COMMIT:=$(short "${aklite_rev}")}"
: "\${FIOCHECK_SOTA_CLIENT:=${sota_client:-aktualizr-lite}}"

# composectl (${composectl_rev})
: "\${FIOCHECK_COMPOSECTL_COMMIT:=$(short "${composectl_rev}")}"

# fioconfig (${fioconfig_rev})
: "\${FIOCHECK_FIOCONFIG_UNITS:=${fioconfig_units}}"

# device register (${register_rev})
EOF
    if [ "${kind}" = "meta-lmp" ]; then
        cat <<EOF
: "\${FIOCHECK_REGISTER_BIN:=lmp-device-register}"
EOF
    else
        cat <<EOF
: "\${FIOCHECK_REGISTER_BIN:=fio-device-register}"
: "\${FIOCHECK_REGISTER_ABSENT_BINS:=lmp-device-register}"
EOF
        [ -n "${daemon_config}" ] && cat <<EOF

# docker-moby daemon.json (dynamic-layers/virtualization-layer)
: "\${FIOCHECK_DOCKER_DAEMON_JSON:=/usr/lib/docker/daemon.json}"
: "\${FIOCHECK_DOCKER_DAEMON_CONFIG:=${daemon_config}}"
EOF
    fi
}

if [ -n "${out}" ]; then
    mkdir -p "$(dirname "${out}")"
    emit > "${out}"
    echo "wrote ${out} (${kind} ${series} @ ${rev})"
else
    emit
fi
